    return when {
        key.startsWith("bgm") -> bangumiSmilesMap[key]
        key.startsWith("musume_") -> bangumiMusumeSmilesMap[key]
        key.startsWith("blake_") -> bangumiBlakeSmilesMap[key]
        key.startsWith("bmo") -> "http://localhost/bmo?code=$key"
        else -> null
    }
}